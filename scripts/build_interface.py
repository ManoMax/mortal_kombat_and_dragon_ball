#!/usr/bin/env python3
"""Generate a progressive arcade recolor from the licensed distributed motif."""
from pathlib import Path
import re
ROOT = Path(__file__).resolve().parents[1]

def main():
    text=(ROOT/'assets-source/fight-base.def').read_text()
    text=text.replace('counter.palfx.mul = 256, 0, 0','counter.palfx.mul = 256, 192, 96')
    text=text.replace('p1.win.text = "%s"','p1.win.text = "%s WINS"').replace('p2.win.text = "%s"','p2.win.text = "%s WINS"')
    # Tint life fronts in every team layout; leave native animation timing intact.
    text=re.sub(r'^(p[12]\.front(?:100|50|25)?\.spr[^\n]*)$', lambda m: m[0]+'\n'+m[1].split('.spr')[0]+'.palfx.mul = '+('256,180,96' if m[0].startswith('p1') else '160,144,256'), text, flags=re.M)
    (ROOT/'engine/data/fight.def').write_text('; Generated by scripts/build_interface.py\n'+text)

if __name__ == '__main__': main()
